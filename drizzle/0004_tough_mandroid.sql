-- Convert the English prose history into keys + params so a bilingual admin can render it in
-- either language. The messages were machine-generated by updateRequest(), so they parse
-- reliably; anything that does not parse is kept verbatim under the 'legacy' key rather than
-- guessed at, and still renders.
DO $$
DECLARE
  r       record;
  part    text;
  m       text[];
  changes jsonb;
  parsed  boolean;
BEGIN
  FOR r IN SELECT id, message FROM request_events WHERE event IS NULL OR event = 'legacy' LOOP
    IF r.message = 'Request received via website' THEN
      UPDATE request_events SET event = 'received', params = NULL WHERE id = r.id;
      CONTINUE;
    END IF;

    changes := '[]'::jsonb;
    parsed  := true;

    FOREACH part IN ARRAY string_to_array(r.message, ' · ') LOOP
      m := regexp_match(part, '^Status: ([a-z]+) → ([a-z]+)$');
      IF m IS NOT NULL THEN
        changes := changes || jsonb_build_object('kind', 'status', 'from', m[1], 'to', m[2]);
        CONTINUE;
      END IF;

      m := regexp_match(part, '^Quote: (—|€[0-9,]+(\.[0-9]{1,2})?) → (—|€[0-9,]+(\.[0-9]{1,2})?)$');
      IF m IS NOT NULL THEN
        changes := changes || jsonb_build_object(
          'kind', 'quote',
          'from', CASE WHEN m[1] = '—' THEN NULL::text ELSE replace(replace(m[1], '€', ''), ',', '') END,
          'to',   CASE WHEN m[3] = '—' THEN NULL::text ELSE replace(replace(m[3], '€', ''), ',', '') END
        );
        CONTINUE;
      END IF;

      IF part = 'Internal notes updated' THEN
        changes := changes || jsonb_build_object('kind', 'notes');
        CONTINUE;
      END IF;

      parsed := false;
      EXIT;
    END LOOP;

    IF parsed THEN
      UPDATE request_events SET event = 'changes', params = jsonb_build_object('changes', changes) WHERE id = r.id;
    ELSE
      UPDATE request_events SET event = 'legacy', params = jsonb_build_object('text', r.message) WHERE id = r.id;
    END IF;
  END LOOP;
END $$;
